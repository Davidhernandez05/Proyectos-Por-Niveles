// AND OR y NOT

let mayor = true;
let menor = false;

/**
 * AND -> &&:
 * Se cumple cuando los dos son verdades.
 */
console.log('operador AND: ', mayor && menor);

/**
 * OR -> ||
 * Se cumple cuando uno de los dos es verdadero.
 * O ambos lo son.
 */

console.log('Operador OR: ', mayor || menor);

/**
 * NOT -> !
 * Invierte el valor que le estamos asignando.
 * Ejemplo:
 * True pasa a ser False.
 */

console.log('Operador NOT: ', !mayor);