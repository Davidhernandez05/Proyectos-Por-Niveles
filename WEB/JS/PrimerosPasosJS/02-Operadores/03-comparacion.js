let a = 5;

//Relaciones:

console.log(a > 6);
console.log(a < 6);
console.log(a >= 6);
console.log(a <= 6);

// Igualdad:
//Valida si el valor es igual:
console.log(a == 6);
//Valida si el valor es diferente:
console.log(a != 6);

// Estas son las mas utilizadas en igualdad.
// Valida si tanto el tipo como el valor son iguales y en este caso retorna true:
console.log(a === 6);
//Valida si el valor o el tipo son diferentes.
console.log(a !== 6);