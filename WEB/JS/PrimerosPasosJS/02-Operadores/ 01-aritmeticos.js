let a = 5, b = 7;

// Operadores matematicos:
console.log(a + b, 'Adicion'); //Operador de adicion
console.log(a - b, 'Resta'); //Operador de resta
console.log(a * b, 'multiplicacion'); //Operador de multiplicacion
console.log(a / b, 'division'); //Operador de division
console.log(a % b, 'modulo'); //Operador de modulo
console.log(a ** b, 'potencia');//Operador de potencia

//Operador de incremento:
//Incrementar el valor antes de imprimir la variable.
console.log(++a, 'Antes');
//Incrementar el valor despues de imprimir la variable.
console.log(a++, 'Despues');
console.log(a);

//Operadores de decrementacion - decrement
//Decrementa el valor en 1 antes de imprimir la variable
console.log(--a, 'antes');
//Decrementa el valor en 1 despues de imprimir la variable.
console.log(a--, 'despues');
console.log(a);